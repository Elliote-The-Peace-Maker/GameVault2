begin;

-- Give guests only the public reads already covered by anonymous RLS policies.
grant select on table
  public.challenge_entries,
  public.challenges,
  public.comments,
  public.communities,
  public.community_members,
  public.creator_profiles,
  public.game_platforms,
  public.games,
  public.map_markers,
  public.media_items,
  public.membership_addons,
  public.membership_plans,
  public.platforms,
  public.post_reactions,
  public.posts,
  public.stream_links
to anon;

-- Client workflows use SECURITY DEFINER actions for these records; never let
-- regular accounts write moderator roles or create conversation membership rows.
revoke insert, update, delete on table public.user_roles from authenticated;
revoke insert, update, delete on table public.conversations from authenticated;
revoke insert, update, delete on table public.conversation_members from authenticated;

-- Notifications are generated by trusted triggers; members only read and mark
-- their own notifications. Reactions/messages/reports don't need these writes.
revoke insert, delete on table public.notifications from authenticated;
revoke update on table public.post_reactions from authenticated;
revoke update on table public.messages from authenticated;
revoke delete on table public.moderation_reports from authenticated;
revoke delete on table public.profiles from authenticated;

-- These object-level privileges are not used by the web API and bypass the
-- row-oriented access model. Keep them off client roles on existing tables.
revoke truncate, references, trigger on all tables in schema public from anon, authenticated;

-- Make all future public-schema tables/functions opt-in for the Data API.
alter default privileges for role postgres in schema public
  revoke all on tables from anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  revoke execute on functions from public, anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  revoke all on sequences from anon, authenticated, service_role;

commit;

